import { formatTicketAmount } from "@/lib/tickets";

/**
 * Pure helpers for the organizer promotion kit (WhatsApp texts, links, QR poster, share image).
 * Safe on client and server: no I/O, no clock, no environment access.
 */
export type PromoEvent = {
  id: string;
  nome: string;
  dataInicio: string;
  startTime?: string | null;
  endTime?: string | null;
  timezone?: string | null;
  endereco?: string | null;
  isFree?: boolean;
  priceCents?: number | null;
  capacity?: number | null;
  ticketCapacity?: number | null;
  status?: string | null;
};

export type PromoVariantId = "curto" | "convite" | "ultimos";
export type PromoVariant = { id: PromoVariantId; label: string; description: string };

const DEFAULT_TIMEZONE = "America/Sao_Paulo";

/** Only published events are publicly reachable, so only they can be promoted. */
export function isPromotable(status: string | null | undefined): boolean {
  return status === "PUBLISHED";
}

/** Absolute public URL of the event. Uses only the origin; returns null for non-http(s) or invalid origins. */
export function promoEventUrl(origin: string, eventId: string): string | null {
  try {
    const base = new URL(origin);
    if (!["http:", "https:"].includes(base.protocol)) return null;
    return new URL("/eventos/" + encodeURIComponent(eventId), base.origin).href;
  } catch {
    return null;
  }
}

/** URL without protocol, for printed posters. */
export function promoShortUrl(url: string): string {
  return url.replace(/^https?:\/\//, "").replace(/\/$/, "");
}

/** Share card generated by app/eventos/[id]/opengraph-image.tsx (1200x630). */
export function promoShareImagePath(eventId: string): string {
  return "/eventos/" + encodeURIComponent(eventId) + "/opengraph-image/card";
}

export function promoQrFileName(event: Pick<PromoEvent, "nome">): string {
  const slug = event.nome.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase()
    .replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 60);
  return `qr-${slug || "evento"}.png`;
}

export function whatsappShareUrl(text: string): string {
  return "https://wa.me/?text=" + encodeURIComponent(text);
}

/** "Gratuito", "R$ 45,90" or null when the price is unknown (the message then leaves it out). */
export function promoPriceText(event: Pick<PromoEvent, "isFree" | "priceCents">): string | null {
  if (event.isFree) return "Gratuito";
  return typeof event.priceCents === "number" && event.priceCents > 0 ? formatTicketAmount(event.priceCents) : null;
}

function formatDay(value: string, timezone: string): string | null {
  const day = /^(\d{4})-(\d{2})-(\d{2})$/.exec(value);
  const options: Intl.DateTimeFormatOptions = { weekday: "long", day: "numeric", month: "long", year: "numeric" };
  try {
    if (day) {
      const date = new Date(Date.UTC(Number(day[1]), Number(day[2]) - 1, Number(day[3]), 12));
      return Number.isNaN(date.getTime()) ? null : new Intl.DateTimeFormat("pt-BR", { ...options, timeZone: "UTC" }).format(date);
    }
    const date = new Date(value);
    return Number.isNaN(date.getTime()) ? null : new Intl.DateTimeFormat("pt-BR", { ...options, timeZone: timezone }).format(date);
  } catch {
    return null;
  }
}

/** "sábado, 12 de dezembro de 2099, às 20:00" or "Data a confirmar". */
export function promoDateText(event: Pick<PromoEvent, "dataInicio" | "startTime" | "timezone">): string {
  const day = formatDay(event.dataInicio, event.timezone || DEFAULT_TIMEZONE);
  if (!day) return "Data a confirmar";
  return event.startTime && /^\d{2}:\d{2}$/.test(event.startTime) ? `${day}, às ${event.startTime}` : day;
}

function promoCapacity(event: Pick<PromoEvent, "capacity" | "ticketCapacity">): number | null {
  const value = event.capacity ?? event.ticketCapacity ?? null;
  return typeof value === "number" && value > 0 ? value : null;
}

export function promoVariants(event: Pick<PromoEvent, "capacity" | "ticketCapacity">): PromoVariant[] {
  const variants: PromoVariant[] = [
    { id: "curto", label: "Curto", description: "Direto ao ponto, ideal para grupos." },
    { id: "convite", label: "Convite", description: "Tom pessoal para mandar a amigos." },
  ];
  if (promoCapacity(event)) variants.push({ id: "ultimos", label: "Últimos ingressos", description: "Reforça que as vagas são limitadas." });
  return variants;
}

/** Ready-to-send Portuguese message. WhatsApp renders *texto* in bold. */
export function buildPromoMessage(event: PromoEvent, variant: PromoVariantId, url: string): string {
  const date = promoDateText(event);
  const place = event.endereco?.trim() || null;
  const price = promoPriceText(event);
  const capacity = promoCapacity(event);
  const details = [
    `📅 ${date}`,
    place ? `📍 ${place}` : null,
    price ? `🎟️ ${price}` : null,
  ].filter((line): line is string => Boolean(line));

  if (variant === "ultimos" && capacity) {
    return [
      `⏳ *Últimos ingressos para ${event.nome}!*`,
      "",
      ...details,
      `👥 Apenas ${capacity} lugares`,
      "",
      `Garanta o seu antes que acabe: ${url}`,
    ].join("\n");
  }
  if (variant === "convite") {
    return [
      `Oi! Vai rolar *${event.nome}* e eu queria muito te ver lá. 🎉`,
      "",
      ...details,
      "",
      `Todos os detalhes e a inscrição estão aqui: ${url}`,
      "",
      "Bora?",
    ].join("\n");
  }
  return [`🎉 *${event.nome}*`, ...details, "", url].join("\n");
}
